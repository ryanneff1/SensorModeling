#!/usr/bin/env python3
"""
Plot fitted k_on, k_off, and K_D versus an automatically detected sweep parameter.

Designed for CSV files generated by fit_1to1_kinetics_sweep_aware.py, while
remaining backward compatible with earlier fit CSVs that contain recognizable
sweep columns such as pore_diameter_m or association_concentration_M.

Notebook example
----------------
from plot_kinetic_parameter_sweep import (
    load_kinetic_sweep,
    summarize_kinetic_sweep,
    plot_kinetic_sweep,
)

data = load_kinetic_sweep("one_to_one_kinetics.csv")
fig, axes = plot_kinetic_sweep(data)

Command-line example
--------------------
python plot_kinetic_parameter_sweep.py \
    --input-csv one_to_one_kinetics.csv \
    --output kinetics_vs_sweep.png \
    --summary-csv kinetics_vs_sweep_summary.csv
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, Optional, Sequence, Tuple

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


PARAMETERS = {
    "k_on": {
        "candidates": (
            "k_on_eff_M_inv_s",
            "k_on_M_inv_s",
            "k_on",
        ),
        "label": r"$k_{\mathrm{on}}$ (M$^{-1}$ s$^{-1}$)",
        "title": r"$k_{\mathrm{on}}$",
    },
    "k_off": {
        "candidates": (
            "k_off_eff_s_inv",
            "k_off_s_inv",
            "k_off_s",
            "k_off",
        ),
        "label": r"$k_{\mathrm{off}}$ (s$^{-1}$)",
        "title": r"$k_{\mathrm{off}}$",
    },
    "K_D": {
        "candidates": (
            "K_D_eff_M",
            "Kd_M",
            "K_D_M",
            "K_D",
        ),
        "label": r"$K_D$ (M)",
        "title": r"$K_D$",
    },
}


SWEEP_INFO = {
    "pore_diameter_m": {
        "label": "Pore diameter",
        "display_scale": 1e9,
        "display_unit": "nm",
    },
    "pore_depth_m": {
        "label": "Pore height/depth",
        "display_scale": 1e9,
        "display_unit": "nm",
    },
    "pore_height_m": {
        "label": "Pore height",
        "display_scale": 1e9,
        "display_unit": "nm",
    },
    "association_concentration_M": {
        "label": "Association concentration",
        "display_scale": 1e9,
        "display_unit": "nM",
    },
    "ligand_conc_M": {
        "label": "Ligand concentration",
        "display_scale": 1e9,
        "display_unit": "nM",
    },
    "receptor_density_m2": {
        "label": "Receptor density",
        "display_scale": 1.0,
        "display_unit": r"m$^{-2}$",
    },
    "spike_density_m2": {
        "label": "Primary spike density",
        "display_scale": 1.0,
        "display_unit": r"m$^{-2}$",
    },
    "branch_levels": {
        "label": "Branch levels",
        "display_scale": 1.0,
        "display_unit": "",
    },
    "branches_per_segment_mean": {
        "label": "Mean branches per segment",
        "display_scale": 1.0,
        "display_unit": "",
    },
}

# Priority for inferring legacy CSVs without sweep_parameter/sweep_value.
LEGACY_SWEEP_COLUMNS = (
    "pore_diameter_m",
    "pore_depth_m",
    "pore_height_m",
    "receptor_density_m2",
    "spike_density_m2",
    "branch_levels",
    "branches_per_segment_mean",
    "association_concentration_M",
    "ligand_conc_M",
)


def _find_column(
    dataframe: pd.DataFrame,
    candidates: Sequence[str],
    *,
    required: bool = True,
) -> Optional[str]:
    for column in candidates:
        if column in dataframe.columns:
            return column

    if required:
        raise KeyError(
            "Could not find any of these expected columns: "
            + ", ".join(candidates)
        )

    return None


def _kinetic_columns(dataframe: pd.DataFrame) -> Dict[str, str]:
    return {
        name: _find_column(dataframe, spec["candidates"])
        for name, spec in PARAMETERS.items()
    }


def _replicate_column(dataframe: pd.DataFrame) -> Optional[str]:
    return _find_column(
        dataframe,
        ("replicate", "replicate_id"),
        required=False,
    )


def _success_mask(dataframe: pd.DataFrame) -> pd.Series:
    for column in (
        "optimizer_success",
        "fit_success",
        "association_fit_success",
    ):
        if column not in dataframe.columns:
            continue

        values = dataframe[column]

        if pd.api.types.is_bool_dtype(values):
            return values.fillna(False)

        return (
            values.astype(str)
            .str.strip()
            .str.lower()
            .isin(("true", "1", "yes"))
        )

    return pd.Series(True, index=dataframe.index, dtype=bool)


def _infer_sweep_parameter(dataframe: pd.DataFrame) -> str:
    """Return one unambiguous sweep parameter from a fit CSV."""
    if "sweep_parameter" in dataframe.columns:
        values = (
            dataframe["sweep_parameter"]
            .dropna()
            .astype(str)
            .str.strip()
        )
        values = values[values.ne("")].unique()

        if len(values) == 1:
            return str(values[0])

        if len(values) > 1:
            raise ValueError(
                "The CSV contains multiple sweep_parameter values: "
                f"{values.tolist()}. Plot one sweep at a time or pass "
                "sweep_parameter explicitly to load_kinetic_sweep()."
            )

    varying = []

    for column in LEGACY_SWEEP_COLUMNS:
        if column not in dataframe.columns:
            continue

        values = pd.to_numeric(dataframe[column], errors="coerce")
        finite = values[np.isfinite(values)]

        if finite.nunique() > 1:
            varying.append(column)

    if len(varying) == 1:
        return varying[0]

    if len(varying) == 0:
        raise ValueError(
            "Could not identify a swept parameter. The preferred fit output "
            "contains sweep_parameter and sweep_value columns."
        )

    # Association concentration often varies incidentally in concentration
    # sweeps but geometry columns may also be repeated metadata. If exactly one
    # non-concentration variable varies, prefer it.
    non_concentration = [
        value
        for value in varying
        if value not in {"association_concentration_M", "ligand_conc_M"}
    ]

    if len(non_concentration) == 1:
        return non_concentration[0]

    raise ValueError(
        "Multiple candidate sweep parameters vary in this CSV: "
        f"{varying}. Supply sweep_parameter explicitly."
    )


def _extract_sweep_values(
    dataframe: pd.DataFrame,
    sweep_parameter: str,
) -> pd.Series:
    if "sweep_value_numeric" in dataframe.columns:
        values = pd.to_numeric(
            dataframe["sweep_value_numeric"],
            errors="coerce",
        )
        if np.any(np.isfinite(values)):
            return values

    if "sweep_value" in dataframe.columns:
        values = pd.to_numeric(dataframe["sweep_value"], errors="coerce")
        if np.any(np.isfinite(values)):
            return values

    if sweep_parameter in dataframe.columns:
        return pd.to_numeric(dataframe[sweep_parameter], errors="coerce")

    # Common legacy unit aliases.
    aliases = {
        "pore_diameter_m": ("pore_diameter_nm", 1e-9),
        "pore_depth_m": ("pore_depth_nm", 1e-9),
    }

    if sweep_parameter in aliases:
        column, factor = aliases[sweep_parameter]
        if column in dataframe.columns:
            return pd.to_numeric(dataframe[column], errors="coerce") * factor

    raise KeyError(
        f"Could not find values for sweep parameter {sweep_parameter!r}."
    )


def _parameter_label(dataframe: pd.DataFrame, parameter: str) -> str:
    if "sweep_parameter_label" in dataframe.columns:
        values = dataframe["sweep_parameter_label"].dropna().astype(str).unique()
        if len(values) == 1 and values[0].strip():
            return values[0]

    return SWEEP_INFO.get(
        parameter,
        {"label": parameter.replace("_", " ").capitalize()},
    )["label"]


def _display_sweep_values(
    raw_values: np.ndarray,
    parameter: str,
) -> Tuple[np.ndarray, str, str]:
    info = SWEEP_INFO.get(
        parameter,
        {
            "label": parameter.replace("_", " ").capitalize(),
            "display_scale": 1.0,
            "display_unit": "",
        },
    )

    scale = float(info["display_scale"])
    unit = str(info["display_unit"])
    label = str(info["label"])

    return raw_values * scale, label, unit


def load_kinetic_sweep(
    input_csv: str | Path,
    *,
    sweep_parameter: Optional[str] = None,
) -> pd.DataFrame:
    """
    Load a fitted kinetic CSV and standardize its sweep/kinetic columns.

    Returned columns include:
        sweep_parameter
        sweep_value
        sweep_value_display
        replicate
        k_on
        k_off
        K_D
    """
    input_csv = Path(input_csv).expanduser().resolve()
    data = pd.read_csv(input_csv)

    kinetic_columns = _kinetic_columns(data)
    data = data.loc[_success_mask(data)].copy()

    for column in kinetic_columns.values():
        data[column] = pd.to_numeric(data[column], errors="coerce")

    if sweep_parameter is None:
        sweep_parameter = _infer_sweep_parameter(data)

    sweep_parameter = str(sweep_parameter)
    raw_sweep = _extract_sweep_values(data, sweep_parameter)

    rep_col = _replicate_column(data)
    replicate = (
        pd.to_numeric(data[rep_col], errors="coerce")
        if rep_col is not None
        else pd.Series(np.arange(1, len(data) + 1), index=data.index)
    )

    sweep_display, label, unit = _display_sweep_values(
        raw_sweep.to_numpy(dtype=float),
        sweep_parameter,
    )

    standardized = pd.DataFrame(
        {
            "sweep_parameter": sweep_parameter,
            "sweep_parameter_label": _parameter_label(data, sweep_parameter),
            "sweep_parameter_unit": unit,
            "sweep_value": raw_sweep.to_numpy(dtype=float),
            "sweep_value_display": sweep_display,
            "replicate": replicate.to_numpy(),
            "k_on": data[kinetic_columns["k_on"]].to_numpy(dtype=float),
            "k_off": data[kinetic_columns["k_off"]].to_numpy(dtype=float),
            "K_D": data[kinetic_columns["K_D"]].to_numpy(dtype=float),
        }
    )

    # Preserve useful metadata if available.
    for column in (
        "association_concentration_M",
        "association_r_squared",
        "dissociation_r_squared",
        "joint_r_squared",
        "roughness_factor",
        "nanospike_primary_count",
        "nanospike_segment_count",
    ):
        if column in data.columns:
            standardized[column] = data[column].to_numpy()

    finite_sweep = np.isfinite(
        standardized["sweep_value"].to_numpy(dtype=float)
    )

    finite_kinetic = np.zeros(len(standardized), dtype=bool)
    for parameter in ("k_on", "k_off", "K_D"):
        finite_kinetic |= np.isfinite(
            standardized[parameter].to_numpy(dtype=float)
        )

    standardized = standardized.loc[
        finite_sweep & finite_kinetic
    ].copy()

    if standardized.empty:
        raise ValueError("No usable successful fit rows remain after cleaning.")

    return standardized.sort_values(
        ["sweep_value", "replicate"]
    ).reset_index(drop=True)


def summarize_kinetic_sweep(data: pd.DataFrame) -> pd.DataFrame:
    """Calculate mean, SD, SEM, and n for k_on, k_off, and K_D."""
    rows = []

    for sweep_value, subset in data.groupby("sweep_value", sort=True):
        display_value = float(subset["sweep_value_display"].iloc[0])

        for parameter in ("k_on", "k_off", "K_D"):
            values = pd.to_numeric(subset[parameter], errors="coerce").to_numpy(dtype=float)
            values = values[np.isfinite(values) & (values > 0)]
            n = len(values)

            if n == 0:
                mean = sd = sem = np.nan
            elif n == 1:
                mean = float(values[0])
                sd = sem = 0.0
            else:
                mean = float(np.mean(values))
                sd = float(np.std(values, ddof=1))
                sem = sd / np.sqrt(n)

            rows.append(
                {
                    "sweep_parameter": subset["sweep_parameter"].iloc[0],
                    "sweep_parameter_label": subset["sweep_parameter_label"].iloc[0],
                    "sweep_parameter_unit": subset["sweep_parameter_unit"].iloc[0],
                    "sweep_value": float(sweep_value),
                    "sweep_value_display": display_value,
                    "parameter": parameter,
                    "mean": mean,
                    "sd": sd,
                    "sem": sem,
                    "n": n,
                }
            )

    return pd.DataFrame(rows)


def plot_parameter(
    data: pd.DataFrame,
    parameter: str,
    *,
    ax=None,
    show_replicates: bool = True,
    show_sem: bool = True,
    log_y: bool = True,
    log_x: bool = False,
    point_jitter_fraction: float = 0.015,
):
    """Plot one fitted kinetic parameter against the detected sweep variable."""
    if parameter not in PARAMETERS:
        raise ValueError(f"parameter must be one of {tuple(PARAMETERS)}.")

    if ax is None:
        _, ax = plt.subplots(figsize=(7, 5))

    summary = summarize_kinetic_sweep(data)
    summary = summary.loc[summary["parameter"].eq(parameter)].sort_values(
        "sweep_value_display"
    )

    x_unique = np.sort(data["sweep_value_display"].unique())
    if len(x_unique) > 1:
        x_span = float(np.ptp(x_unique))
        jitter_scale = point_jitter_fraction * x_span
    else:
        jitter_scale = 0.0

    rng = np.random.default_rng(0)

    if show_replicates:
        values = pd.to_numeric(data[parameter], errors="coerce").to_numpy(dtype=float)
        x = data["sweep_value_display"].to_numpy(dtype=float)
        mask = np.isfinite(x) & np.isfinite(values) & (values > 0)
        jitter = (
            rng.uniform(-jitter_scale, jitter_scale, size=np.count_nonzero(mask))
            if jitter_scale > 0 and not log_x
            else np.zeros(np.count_nonzero(mask))
        )
        ax.scatter(
            x[mask] + jitter,
            values[mask],
            s=32,
            alpha=0.6,
            zorder=2,
            label="Replicates",
        )

    x_summary = summary["sweep_value_display"].to_numpy(dtype=float)
    means = summary["mean"].to_numpy(dtype=float)
    sem = summary["sem"].to_numpy(dtype=float) if show_sem else np.zeros(len(summary))

    valid = np.isfinite(x_summary) & np.isfinite(means) & (means > 0)

    ax.errorbar(
        x_summary[valid],
        means[valid],
        yerr=sem[valid],
        fmt="o-",
        markersize=7,
        capsize=4,
        linewidth=1.8,
        zorder=3,
        label="Mean ± SEM" if show_sem else "Mean",
    )

    sweep_label = str(data["sweep_parameter_label"].iloc[0])
    sweep_unit = str(data["sweep_parameter_unit"].iloc[0])
    xlabel = sweep_label + (f" ({sweep_unit})" if sweep_unit else "")

    ax.set_xlabel(xlabel)
    ax.set_ylabel(PARAMETERS[parameter]["label"])
    ax.set_title(PARAMETERS[parameter]["title"])

    if log_y:
        ax.set_yscale("log")
    if log_x:
        if np.any(x_summary <= 0):
            raise ValueError("log_x=True requires strictly positive sweep values.")
        ax.set_xscale("log")

    # Branch level is an integer experimental variable; keep exact integer ticks.
    if str(data["sweep_parameter"].iloc[0]) == "branch_levels":
        ax.set_xticks(x_unique)

    ax.grid(alpha=0.25)
    return ax


def plot_kinetic_sweep(
    data: pd.DataFrame,
    *,
    figsize: Tuple[float, float] = (15, 4.8),
    show_replicates: bool = True,
    show_sem: bool = True,
    log_y: bool = True,
    log_x: bool = False,
):
    """Create k_on, k_off, and K_D panels versus the automatically detected sweep."""
    fig, axes = plt.subplots(1, 3, figsize=figsize)

    for ax, parameter in zip(axes, ("k_on", "k_off", "K_D")):
        plot_parameter(
            data,
            parameter,
            ax=ax,
            show_replicates=show_replicates,
            show_sem=show_sem,
            log_y=log_y,
            log_x=log_x,
        )

    sweep_label = str(data["sweep_parameter_label"].iloc[0])
    fig.suptitle(f"Effective binding kinetics vs {sweep_label.lower()}", y=1.02)
    fig.tight_layout()
    return fig, axes


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Automatically identify the swept parameter in a fitted-kinetics CSV "
            "and plot k_on, k_off, and K_D versus that parameter."
        )
    )

    parser.add_argument("--input-csv", type=Path, required=True)
    parser.add_argument(
        "--sweep-parameter",
        default=None,
        help="Optional explicit override if automatic sweep detection is ambiguous.",
    )
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument("--summary-csv", type=Path, default=None)
    parser.add_argument("--no-replicates", action="store_true")
    parser.add_argument("--no-sem", action="store_true")
    parser.add_argument("--linear-y", action="store_true")
    parser.add_argument("--log-x", action="store_true")
    parser.add_argument("--dpi", type=int, default=300)

    return parser


def main() -> None:
    args = build_parser().parse_args()

    data = load_kinetic_sweep(
        args.input_csv,
        sweep_parameter=args.sweep_parameter,
    )

    parameter = str(data["sweep_parameter"].iloc[0])
    label = str(data["sweep_parameter_label"].iloc[0])
    values = np.sort(data["sweep_value"].unique())

    print(f"Detected sweep parameter: {parameter} ({label})")
    print(f"Sweep values: {values.tolist()}")
    print(f"Successful fit rows: {len(data)}")

    fig, _ = plot_kinetic_sweep(
        data,
        show_replicates=not args.no_replicates,
        show_sem=not args.no_sem,
        log_y=not args.linear_y,
        log_x=args.log_x,
    )

    if args.output is None:
        plt.show()
    else:
        output = args.output.expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(output, dpi=args.dpi, bbox_inches="tight")
        print(f"Saved figure: {output}")

    if args.summary_csv is not None:
        summary = summarize_kinetic_sweep(data)
        output = args.summary_csv.expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        summary.to_csv(output, index=False)
        print(f"Saved summary: {output}")


if __name__ == "__main__":
    main()
